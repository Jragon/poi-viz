import {
  buildTurningReelCycle,
  getMelTurningLanes,
  type TurningReelConfig,
  type TurningReelDirection
} from "@/lab/experiments/mel-turning/adapter/melBeatGraphAdapter";
import type {
  LowReelCycleState,
  LowReelDirectTurnCandidate,
  LowReelDirectTurnSearchResult,
  LowReelSearchNode
} from "@/lab/experiments/mel-turning/model/lowReelDirectTurnSearch";
import type {
  TurningHand,
  TurningNode,
  TurningTrace,
  TurningTrack
} from "@/lab/experiments/mel-turning/model/turningTypes";

function stateNode(state: LowReelCycleState, hand: TurningHand): LowReelSearchNode {
  return hand === "left" ? state.left : state.right;
}

function traceNode(state: LowReelCycleState, hand: TurningHand, step: number): TurningNode {
  return {
    step,
    ...stateNode(state, hand)
  };
}

function cycleState(cycle: readonly LowReelCycleState[], step: number): LowReelCycleState {
  const normalized = ((step % cycle.length) + cycle.length) % cycle.length;
  const state = cycle[normalized];
  if (!state) throw new Error("Low-reel turn trace requires a non-empty endpoint cycle.");
  return state;
}

function sourceDirection(
  result: LowReelDirectTurnSearchResult,
  hand: TurningHand
): TurningTrack["poiDirection"] {
  const track = buildTurningReelCycle(result.source).tracks.find(
    (candidate) => candidate.hand === hand
  );
  if (!track) throw new Error(`Low-reel source cycle has no ${hand} track.`);
  return track.poiDirection;
}

function buildTrack(
  result: LowReelDirectTurnSearchResult,
  candidate: LowReelDirectTurnCandidate,
  hand: TurningHand
): TurningTrack {
  const sourcePrevious = cycleState(result.sourceCycle, candidate.source.cycleStep - 1);
  const targetNext = cycleState(result.targetCycle, candidate.target.cycleStep + 1);
  const nodes = [
    traceNode(sourcePrevious, hand, 0),
    traceNode(candidate.source, hand, 1),
    traceNode(candidate.target, hand, 2),
    traceNode(targetNext, hand, 3)
  ];

  return {
    id: hand,
    hand,
    poiDirection: sourceDirection(result, hand),
    initialPhase: nodes[0]!.phase,
    nodes
  };
}

function directionSignature(direction: TurningReelDirection): string {
  if (direction.mode === "same") {
    return direction.direction === "clockwise" ? "same-cw" : "same-ccw";
  }
  return direction.flow === "inwards" ? "opposite-in" : "opposite-out";
}

function reelConfigSignature(config: TurningReelConfig): string {
  return [config.left, config.right, directionSignature(config.direction), config.offset].join("-");
}

function searchSignature(result: LowReelDirectTurnSearchResult): string {
  return [
    reelConfigSignature(result.source),
    reelConfigSignature(result.target),
    result.turnDirection
  ].join("-");
}

export function buildLowReelTurningTrace(
  result: LowReelDirectTurnSearchResult,
  candidate: LowReelDirectTurnCandidate
): TurningTrace {
  const canonicalCandidate = result.candidates.find((entry) => entry.id === candidate.id);
  if (!canonicalCandidate) {
    throw new Error(`Candidate ${candidate.id} does not belong to this low-reel search result.`);
  }

  return {
    id: `generated-${searchSignature(result)}-${canonicalCandidate.id}`,
    label: `${result.sourceTiming} ${result.sourcePatternType} → ${result.targetTiming} ${result.targetPatternType}`,
    timing: result.sourceTiming,
    summary: `Exact low-reel alignment ${canonicalCandidate.source.cycleStep + 1} → ${canonicalCandidate.target.cycleStep + 1}; topology ${canonicalCandidate.topologyStatus}.`,
    source: "Generated by the exact low-reel direct-turn search.",
    verificationStatus: "unverified",
    lanes: getMelTurningLanes(),
    tracks: [
      buildTrack(result, canonicalCandidate, "left"),
      buildTrack(result, canonicalCandidate, "right")
    ],
    events: [
      {
        kind: "body-turn",
        afterStep: 1,
        direction: result.turnDirection,
        degrees: 180,
        fromFacing: 0,
        toFacing: 180,
        note: `Source cycle row ${canonicalCandidate.source.cycleStep + 1} enters target cycle row ${canonicalCandidate.target.cycleStep + 1}.`
      }
    ]
  };
}

export function buildLowReelEndpointPreviewTrace(
  config: TurningReelConfig,
  label = "Low-reel endpoint"
): TurningTrace {
  const cycle = buildTurningReelCycle(config);

  return {
    id: `endpoint-${reelConfigSignature(config)}`,
    label,
    timing: cycle.timing,
    summary: `${cycle.timing} ${cycle.patternType} endpoint preview.`,
    source: "Generated from Mel's reel rules.",
    verificationStatus: "unverified",
    lanes: getMelTurningLanes(),
    tracks: cycle.tracks.map((track) => {
      const first = track.nodes[0];
      if (!first) throw new Error(`Low-reel endpoint ${track.hand} track is empty.`);

      return {
        ...track,
        nodes: [
          ...track.nodes,
          {
            ...first,
            step: cycle.cycleSteps
          }
        ]
      };
    }),
    events: []
  };
}
